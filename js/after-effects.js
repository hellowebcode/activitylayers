// Das Layout ist fuer 1920x1080 entworfen. Auf einer anderen Leinwand behaelt
// jedes Element seinen Abstand zur unteren linken Ecke und seine Groesse im
// selben Verhaeltnis - der Faktor ist fuer beide Achsen gleich, damit nichts
// verzerrt. Bei 1920x1080 ist er 1 und alles bleibt, wie es war.
var AE_W=1920, AE_H=1080;
function aeFaktor(c){ return Math.min(c.W/AE_W, c.H/AE_H); }
function aePunkt(c,x,y){ var k=aeFaktor(c); return [x*k, c.H-(AE_H-y)*k]; }
function aeOrt(c,x,y){ return aeXY(aePunkt(c,x,y)); }
function aeMass(c,n){ return aeNum(n*aeFaktor(c)); }

function aeSafeComment(s){
  return String(s == null ? '' : s)
    .replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120);
}
function aeNum(n){ var v=(typeof n==='number'&&isFinite(n))?n:0; return (Math.round(v*1e4)/1e4).toString(); }
function aeStr(s){ return '"'+String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/\r?\n/g,'\\n')+'"'; }
function aeCol(hex){ var c=hexToRgb(hex); return '['+aeNum(c[0]/255)+','+aeNum(c[1]/255)+','+aeNum(c[2]/255)+']'; }
function aeXY(p){ return '['+aeNum(p[0])+','+aeNum(p[1])+']'; }
function aeList(arr){ return '['+arr.join(',')+']'; }
function aePts(pts){ var o=[]; for(var i=0;i<pts.length;i++) o.push(aeXY(pts[i])); return aeList(o); }
function aeKf(kfs,dec){
  var d=(dec==null)?3:dec, o=[], m=Math.pow(10,d);
  for(var i=0;i<kfs.length;i++){
    var v=kfs[i][1];
    o.push('['+kfs[i][0]+','+(Array.isArray(v)?aeXY(v):(Math.round(v*m)/m))+']');
  }
  return aeList(o);
}
function aeDuration(){
  var c=cfg();
  var fps=parseFloat(c.fps)||30;
  if(!speedData.length) return 10;
  var drift=parseFloat(c.driftFactor)||1.0;
  var offset=parseFloat(c.offset)||0;
  var span=(speedData[speedData.length-1].time-speedData[0].time)/1000*drift+offset;
  return Math.max(1, Math.ceil((span+1)*fps)/fps);
}

