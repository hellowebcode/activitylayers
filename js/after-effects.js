function buildElevJsx(){
  var c=cfg();
  var elevPts=rawPoints.filter(function(p){return p.ele!==null && !isNaN(p.ele);});
  if(elevPts.length<2) return null;
  var iW=Math.min(c.W, parseFloat(c.elevW)||c.W);
  var iH=Math.min(c.H, parseFloat(c.elevH)||300);
  var lw=parseFloat(c.elevLineW)||2;
  var so=zahlOderVorgabe(c.elevShadowOffset,4);
  var fillOn=c.elevFill==='1';
  // Das Profil rechnet in Leinwandkoordinaten; der Anker verschiebt es im
  // Entwurfsmass und wird dafuer mitskaliert.
  // Das Profil wird waagerecht mittig gezeichnet. Der Anker nennt dagegen die
  // Lage am linken Rand, deshalb zaehlt hier die Strecke vom gezeichneten Ort
  // zum Ziel, nicht der Ankerversatz selbst.
  var massElev={b:iW/aeFaktor(c), h:iH/aeFaktor(c)};
  var linksX=ANKER_RAND+massElev.b/2, untenY=ENTWURF_H-120-massElev.h/2;
  var vs=ankerVersatz(c,'elev',massElev,linksX,untenY);
  var vdx=(linksX+vs.dx)-ENTWURF_W/2, vdy=(untenY+vs.dy)-untenY;
  var ox=(c.W-iW)/2+vdx*aeFaktor(c), oy=c.H-iH-120*aeFaktor(c)+vdy*aeFaktor(c);
  var xy=buildElevXY(elevPts,iW,iH,0);
  var pts=[],i;
  for(i=0;i<xy.xs.length;i++) pts.push([ox+xy.xs[i], oy+xy.ys[i]]);
  var closed=pts.slice();
  closed.push([ox+xy.xs[xy.xs.length-1], oy+iH]);
  closed.push([ox+xy.xs[0], oy+iH]);
  var dotKf=aePathKeys(elevPts,pts);
  var L=[aeHead('Elevation Overlay')];
  L.push('  var PTS='+aePts(pts)+';');
  if(fillOn){
    L.push('  var fl=shapeLayer("Elevation Fill"), fg=grpOf(fl,"Area");');
    L.push('  addPath(fg,'+aePts(closed)+',true);');
    L.push('  addFill(fg,'+aeCol(c.elevFillColor)+');');
  }
  L.push('  var sh=shapeLayer("Elevation Shadow"), sg=grpOf(sh,"Path");');
  L.push('  addPath(sg,PTS,false);');
  L.push('  addStroke(sg,'+aeCol(c.elevShadowColor)+','+aeNum(lw*SHADOW_WIDTH_RATIO)+');');
  L.push('  tf(sh,"ADBE Position").setValue([0,'+aeNum(so)+']);');
  L.push('  var ln=shapeLayer("Elevation Line"), lg=grpOf(ln,"Path");');
  L.push('  addPath(lg,PTS,false);');
  L.push('  addStroke(lg,'+aeCol(c.elevColor)+','+aeNum(lw)+');');
  L.push('  var dot=shapeLayer("Elevation Dot"), dg=grpOf(dot,"Dot");');
  L.push('  addEllipse(dg,[18,18],[0,0]);');
  L.push('  addFill(dg,'+aeCol(c.elevDotColor)+');');
  L.push('  keys(tf(dot,"ADBE Position"),'+aeKf(dotKf,2)+');');
  // Die Hoehenzahlen am linken Rand. Das Haekchen wirkte bisher nur in der
  // Vorschau auf der Seite.
  if(c.elevLabels){
    var marken=hoehenMarken(xy.minEle, xy.maxEle, c.unit);
    var beschX=ox+Math.max(28, iH*0.18);
    var einzug=Math.max(8, iH*0.06);
    var hoehenY=[oy+einzug, oy+iH/2, oy+iH-einzug];
    var beschGroesse=iH*0.09;
    for(var m=0;m<marken.length;m++){
      L.push('  textLayer("Elevation label '+(m+1)+'",'+aeStr(marken[m])+',['
        +aeNum(beschX)+','+aeNum(hoehenY[m])+'],'+aeNum(beschGroesse)+','+aeCol(c.elevColor)+',true);');
    }
  }
  L.push(aeTail());
  return L.join('\n');
}

function buildHRJsx(){
  var c=cfg();
  if(!hrData.length) return null;
  var sizeEntwurf=(parseFloat(c.hrSize)||0.07)*AE_H;
  var size=sizeEntwurf*aeFaktor(c);
  var kf=buildKeyframeList(hrData,function(p){return p.hr;});
  var HX=250, HY=880;
  var vs=ankerVersatz(c,'hr',OVERLAY_MASSE.hr,HX,HY); HX+=vs.dx; HY+=vs.dy;
  var ort=aeOrt(c,HX+sizeEntwurf*1.2,HY+sizeEntwurf*0.4);
  // Das Herz entsteht im Entwurfsmass und wandert dann als Ganzes auf die
  // Leinwand, damit Form und Ort zusammenbleiben.
  var sE=sizeEntwurf/22, heart=[], t;
  for(t=0;t<Math.PI*2;t+=Math.PI/36){
    var x=16*Math.pow(Math.sin(t),3);
    var y=13*Math.cos(t)-5*Math.cos(2*t)-2*Math.cos(3*t)-Math.cos(4*t);
    heart.push(aePunkt(c, HX+x*sE, HY-y*sE));
  }
  var L=[aeHead('HR Overlay')];
  L.push('  var hl=shapeLayer("Heart"), hg=grpOf(hl,"Heart");');
  L.push('  addPath(hg,'+aePts(heart)+',true);');
  L.push('  addFill(hg,'+aeCol(c.hrHeartColor)+');');
  var zonen = c.hrZones ? zonenDeckkraft(hrData,function(p){return p.hr;},
    parseFloat(c.hrZone2)||140, parseFloat(c.hrZone3)||165) : null;
  if(zonen){
    var farben=[c.hrColor,c.hrColor2,c.hrColor3];
    for(var z=0;z<3;z++){
      L.push('  var z'+z+'=textLayer("HR zone '+(z+1)+'","0",'+ort+','+aeNum(size)+','+aeCol(farben[z])+',false);');
      L.push('  driveText(z'+z+',"HR zone '+(z+1)+'",'+aeKf(kf,0)+',"Math.round(v)+\\"\\";");');
      L.push('  keys(tf(z'+z+',"ADBE Opacity"),'+aeKf(zonen[z],0)+');');
    }
  } else {
    L.push('  var num=textLayer("HR Value","0",'+ort+','+aeNum(size)+','+aeCol(c.hrColor)+',false);');
    L.push('  driveText(num,"Heart Rate",'+aeKf(kf,0)+',"Math.round(v)+\\"\\";");');
  }
  L.push(aeTail());
  return L.join('\n');
}

